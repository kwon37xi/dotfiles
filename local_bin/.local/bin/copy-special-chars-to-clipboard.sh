#!/usr/bin/env bash
# 자주 사용하는 이모지나 특수 문자를 목록에서 선택해서 클립보드로 복사해준다.
ITEMS=(
    "『』"
    "← → ↑ ↓"
    "⇐ ⇒"
    "⇦ ⇧ ⇮ ⇩"
    "☚☛"
    "⬆️↗️➡️↘️⬇️↙️⬅️↖️"
    "✅☑️✔️"
    "℃℉"
    "🌏🧭🏕️🛍️📦🛒🔔📢💻📽️💡📖"
)
# 결과 문자열에 개행이 있어서 tr 로 제거 필요함.
zenity --list --text="특수문자 선택" --column="특수문자" --hide-header --height 500 "${ITEMS[@]}" | tr -d "\n" | wl-copy
